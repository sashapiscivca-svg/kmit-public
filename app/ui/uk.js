// Форма іменника за числом: pl(n, 'символ', 'символи', 'символів').
export function pl(n, one, few, many) {
  const a = n % 10; const b = n % 100;
  return `${n} ${a === 1 && b !== 11 ? one : a >= 2 && a <= 4 && (b < 12 || b > 14) ? few : many}`;
}

// «1 тема, 2 теми, 5 тем».
export function topicsN(n) {
  const a = n % 10; const b = n % 100;
  return `${n} ${a === 1 && b !== 11 ? 'тема' : a >= 2 && a <= 4 && (b < 12 || b > 14) ? 'теми' : 'тем'}`;
}

