//! Каркас класів: клас «готовий», коли для нього є вміст (5 клас, далі за мірою появи пакетів). Інші класи показуються як «скоро» з орієнтовним переліком предметів
//! (без вигаданого вмісту): наповнення потребує методистів (рішення власника). 12 = підготовка до НМТ.

use serde_json::{json, Value};

pub(crate) const READY_GRADE: u8 = 5;
pub(crate) const NMT: u8 = 12;

/// Орієнтовний перелік за типовим навчальним планом; уточнюють методисти.
fn planned(grade: u8) -> &'static [&'static str] {
    match grade {
        6 => &[
            "Українська мова",
            "Українська література",
            "Англійська мова",
            "Математика",
            "Історія України",
            "Всесвітня історія",
            "Біологія",
            "Географія",
            "Інформатика",
        ],
        7..=9 => &[
            "Українська мова",
            "Українська література",
            "Англійська мова",
            "Алгебра",
            "Геометрія",
            "Історія України",
            "Всесвітня історія",
            "Біологія",
            "Географія",
            "Фізика",
            "Хімія",
            "Інформатика",
        ],
        10 | 11 => &[
            "Українська мова",
            "Українська література",
            "Англійська мова",
            "Алгебра і початки аналізу",
            "Геометрія",
            "Історія України",
            "Фізика",
            "Хімія",
            "Біологія",
            "Інформатика",
        ],
        NMT => &[
            "Українська мова",
            "Математика",
            "Історія України",
            "Англійська мова",
        ],
        _ => &[],
    }
}

/// Є вміст для класу.
pub(crate) fn is_ready(grade: u8) -> bool {
    crate::catalog::content_grades().contains(&grade)
}

pub(crate) fn valid(grade: u8) -> bool {
    (READY_GRADE..=NMT).contains(&grade)
}

pub(crate) fn grades_json(current: u8) -> Value {
    let list: Vec<Value> = (READY_GRADE..=NMT)
        .map(|g| {
            json!({
                "grade": g,
                "ready": is_ready(g),
                "planned": planned(g),
            })
        })
        .collect();
    json!({"current": current, "grades": list})
}
