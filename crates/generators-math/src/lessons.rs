//! Уроки-пояснення для всіх одинадцяти навичок курсу (авторські, потребують перегляду методистом, див. Q7).
//!
//! Умови прикладів навмисно лежать поза діапазонами генераторів (тест `tests/lessons.rs` перевіряє це
//! на 20 000 варіантів), тож учень не бачить розв'язку майбутньої задачі.

use tutor_core::figure::Figure;
use tutor_core::lesson::{Lesson, LessonBlock, LessonSource};

/// Уроки математики 5 класу.
pub struct MathLessons;

const ORDINALS: [&str; 7] = [
    "перший",
    "другий",
    "третій",
    "четвертий",
    "п'ятий",
    "шостий",
    "сьомий",
];

pub(crate) fn text(s: &str) -> LessonBlock {
    LessonBlock::Text(s.to_string())
}

pub(crate) fn example(statement: &str, steps: &[&str], result: &str) -> LessonBlock {
    LessonBlock::Example {
        statement: statement.to_string(),
        steps: steps
            .iter()
            .enumerate()
            .map(|(i, s)| format!("Крок {}. {s}", ORDINALS[i]))
            .collect(),
        result: result.to_string(),
    }
}

pub(crate) fn figure(fig: Figure, caption: &str) -> LessonBlock {
    LessonBlock::Figure {
        figure: fig,
        caption: caption.to_string(),
    }
}

pub(crate) fn check(prompt: &str, answer: &str, explanation: &str) -> LessonBlock {
    LessonBlock::SelfCheck {
        prompt: prompt.to_string(),
        answer: answer.to_string(),
        explanation: explanation.to_string(),
    }
}

pub(crate) fn remember(s: &str) -> LessonBlock {
    LessonBlock::Remember(s.to_string())
}

pub(crate) fn lesson(
    skill: &'static str,
    title: &str,
    blocks: Vec<LessonBlock>,
    notes: &[&str],
) -> Lesson {
    Lesson {
        skill,
        title: title.to_string(),
        blocks,
        note_prompts: notes.iter().map(|s| s.to_string()).collect(),
    }
}

