//! Уроки навичок розширення курсу (рішення A20): натуральні числа, рівняння, текстові задачі, рух.
//! Авторські, потребують перегляду методистом (Q7). Умови прикладів лежать поза просторами генераторів;
//! тест `tests/lessons.rs` перевіряє це на 20 000 варіантів і перераховує всі відповіді незалежним розв'язувачем.

use crate::lessons::{check, example, figure, lesson, remember, text};
use tutor_core::figure::Figure;
use tutor_core::lesson::Lesson;

pub(crate) fn by_skill(skill: &str) -> Option<Lesson> {
    Some(match skill {
        "N-ROUND" => n_round(),
        "N-DIVREM" => n_divrem(),
        "N-DIVTEST" => n_divtest(),
        "N-GCD" => n_gcd(),
        "N-LCM" => n_lcm(),
        "N-POWER" => n_power(),
        "EQ-ADD-SUB" => eq_add_sub(),
        "EQ-MUL" => eq_mul(),
        "WORD-1" => word_1(),
        "WORD-2" => word_2(),
        "MOTION" => motion(),
        _ => return crate::lessons_ext2::by_skill(skill),
    })
}

