pub(crate) fn by_skill(skill: &str) -> Option<Lesson> {
    Some(match skill {
        "U-LEN" => u_len(),
        "U-MASS" => u_mass(),
        "U-TIME" => u_time(),
        "G-PERIM" => g_perim(),
        "G-AREA" => g_area(),
        "G-VOL" => g_vol(),
        "A-ANGLE" => a_angle(),
        "F-MIXED" => f_mixed(),
        "F-REDUCE" => f_reduce(),
        "F-OF" => f_of(),
        "P-PCT" => p_pct(),
        "D-MUL10" => d_mul10(),
        "AVG" => avg(),
        _ => return None,
    })
}

